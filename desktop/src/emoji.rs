#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_a_leading_emoji() {
        assert_eq!(leading("🎉 Party"), Some(("🎉", " Party")));
        assert_eq!(leading("Party"), None);
        assert_eq!(leading("👨‍👩‍👧‍👦 Family"), Some(("👨‍👩‍👧‍👦", " Family")));
        assert_eq!(leading("🇫🇷 France"), Some(("🇫🇷", " France")));
        assert_eq!(leading("1️⃣ One"), Some(("1️⃣", " One")));
        assert_eq!(leading("Café"), None);
        assert_eq!(leading("✓ Done"), Some(("✓", " Done")));
    }

    #[test]
    fn one_emoji_and_nothing_else() {
        assert_eq!(single("🎉"), Some("🎉"));
        assert_eq!(single("  🎉  "), Some("🎉"));
        assert_eq!(single("🎉🎉"), None);
        assert_eq!(single("🎉 Party"), None);
        assert_eq!(single("Party"), None);
    }

    #[test]
    fn the_catalog_searches_keywords() {
        let hits = search("book");
        assert!(hits.contains(&"📚"), "{hits:?}");
        assert!(search("🎉").contains(&"🎉"));
        assert_eq!(search("").len(), CATALOG.len());
    }
}
