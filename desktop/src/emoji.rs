//! Emoji in folder names, and the catalog the icon picker shows.
//!
//! A folder's icon is an emoji at the start of its name. The icon therefore lives in the folder
//! name on disk, and Zotebook shows the rest of the name as the folder's label.

use unicode_segmentation::UnicodeSegmentation;

/// Whether `c` can be an emoji on its own. Joiners and modifiers are left out: they only count
/// as part of a sequence that starts with one of these.
pub fn is_emoji(c: char) -> bool {
    matches!(c as u32,
        0x1F000..=0x1FAFF
        | 0x2600..=0x27BF
        | 0x231A..=0x231B
        | 0x2328 | 0x23CF
        | 0x23E9..=0x23F3
        | 0x23F8..=0x23FA
        | 0x25AA..=0x25AB
        | 0x25B6 | 0x25C0
        | 0x25FB..=0x25FE
        | 0x2934..=0x2935
        | 0x2B05..=0x2B07
        | 0x2B1B..=0x2B1C
        | 0x2B50 | 0x2B55
        | 0x3030 | 0x303D | 0x3297 | 0x3299
        | 0x00A9 | 0x00AE | 0x203C | 0x2049 | 0x2122 | 0x2139
        | 0x2194..=0x2199 | 0x21A9..=0x21AA
    )
}

/// Splits a name into its leading emoji, when it has one, and the rest of the name.
pub fn leading(s: &str) -> Option<(&str, &str)> {
    let first = s.graphemes(true).next()?;
    let mut chars = first.chars();
    let keycap = first.contains('\u{20e3}') && chars.next().is_some_and(|c| c.is_ascii_digit() || matches!(c, '#' | '*'));
    (chars.any(is_emoji) || keycap).then(|| (first, &s[first.len()..]))
}

/// One emoji and nothing else, as typed or pasted into the picker.
pub fn single(s: &str) -> Option<&str> {
    let t = s.trim();
    let (e, rest) = leading(t)?;
    rest.trim().is_empty().then_some(e)
}

/// The emoji that match `q` in the catalog, by emoji or by keyword. An empty query shows all.
pub fn search(q: &str) -> Vec<&'static str> {
    let q = q.trim().to_lowercase();
    CATALOG
        .iter()
        .filter(|(e, words)| q.is_empty() || e.contains(&q) || words.split_whitespace().any(|w| w.starts_with(&q)))
        .map(|(e, _)| *e)
        .collect()
}

